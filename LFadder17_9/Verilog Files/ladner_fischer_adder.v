module ladner_fischer_adder (
    input  wire [7:0] A, B,
    input  wire       Cin,
    output wire [7:0] Sum,
    output wire       Cout
);

    // ------------------------------------------------------------------
    // Level 0: Generate (g) and Propagate (p)
    // ------------------------------------------------------------------
    wire [7:0] g = A & B;
    wire [7:0] p = A ^ B;

    // ------------------------------------------------------------------
    // Level 1: Stride 1
    // ------------------------------------------------------------------
    // Bit 0 incorporates Cin
    wire g1_0 = g[0] | (p[0] & Cin);
    
    // Level 1 combinations
    wire g1_1 = g[1] | (p[1] & g1_0);
    wire p1_1 = p[1] & p[0];

    wire g1_3 = g[3] | (p[3] & g[2]);
    wire p1_3 = p[3] & p[2];

    wire g1_5 = g[5] | (p[5] & g[4]);
    wire p1_5 = p[5] & p[4];

    wire g1_7 = g[7] | (p[7] & g[6]);
    wire p1_7 = p[7] & p[6];

    // ------------------------------------------------------------------
    // Level 2: Stride 2
    // ------------------------------------------------------------------
    wire g2_2 = g[2]  | (p[2]  & g1_1);
    
    wire g2_3 = g1_3 | (p1_3 & g1_1);
    wire p2_3 = p1_3 & p1_1;

    wire g2_4 = g[4]  | (p[4]  & g1_3);
    
    wire g2_5 = g1_5 | (p1_5 & g1_3);
    wire p2_5 = p1_5 & p1_3;

    wire g2_6 = g[6]  | (p[6]  & g1_5);
    wire p2_6 = p[6]  & p1_5;

    wire g2_7 = g1_7 | (p1_7 & g1_5);
    wire p2_7 = p1_7 & p1_5;

    // ------------------------------------------------------------------
    // Level 3: Stride 4 (Final Carries)
    // ------------------------------------------------------------------
    wire g3_4 = g2_4 | (p[4]  & g2_3);
    wire g3_5 = g2_5 | (p2_5 & g2_3);
    wire g3_6 = g2_6 | (p2_6 & g2_3);
    wire g3_7 = g2_7 | (p2_7 & g2_3);

    // ------------------------------------------------------------------
    // Final Carry Mapping & Sum Generation
    // ------------------------------------------------------------------
    wire [7:0] c;
    assign c[0] = Cin;
    assign c[1] = g1_0;
    assign c[2] = g1_1;
    assign c[3] = g2_2;
    assign c[4] = g2_3;
    assign c[5] = g3_4;
    assign c[6] = g3_5;
    assign c[7] = g3_6;

    assign Sum  = p ^ c;
    assign Cout = g3_7;

endmodule